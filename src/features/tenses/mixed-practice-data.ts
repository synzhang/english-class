function shuffled<T>(items: T[], random: () => number): T[] {
  const result = [...items]
  for (let index = result.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1))
    ;[result[index], result[swapIndex]] = [result[swapIndex], result[index]]
  }
  return result
}

export function createMixedPracticeRound(random: () => number = Math.random) {
  const selectedByLesson = tenseLessons.map((lesson) => {
    const questions = mixedPracticeQuestions.filter(
      (question) => question.lessonId === lesson.id,
    )
    const question = questions[Math.floor(random() * questions.length)]
    if (!question) throw new Error(`No mixed-practice questions for ${lesson.id}`)
    return { ...question, options: shuffled(question.options, random) }
  })

  return shuffled(selectedByLesson, random)
}
