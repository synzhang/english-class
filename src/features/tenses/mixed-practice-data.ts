export const mixedPracticeQuestions: LessonQuestion[] = mixedQuestionSeeds.map(
  (seed) => {
    const targetLesson = getTenseLessonById(seed.lessonId)
    if (!targetLesson) throw new Error(`Unknown mixed-practice lesson: ${seed.lessonId}`)

    const feedbackByOption = Object.fromEntries(
      seed.choices.map(([choiceLessonId]) => {
        const choiceLesson = getTenseLessonById(choiceLessonId)
        if (!choiceLesson) {
          throw new Error(`Unknown mixed-practice choice: ${choiceLessonId}`)
        }

        const feedback =
          choiceLessonId === seed.lessonId
            ? `正确。${seed.whyCorrect}`
            : `${choiceLesson.title}通常用于${choiceLesson.summary}；但${seed.contrast}，所以这里更适合${targetLesson.title}。`

        return [choiceLessonId, feedback]
      }),
    )

    return {
      id: `mixed-${seed.id}`,
      lessonId: seed.lessonId,
      context: seed.context,
      before: seed.before,
      after: seed.after,
      options: seed.choices.map(([lessonId, label]) => ({ id: lessonId, label })),
      correctOptionId: seed.lessonId,
      feedbackByOption,
      practiceStage: "16 时态混合练习",
    }
  },
)

export const mixedPracticeQuestionIds = mixedPracticeQuestions.map(
  (question) => question.id,
)

